/**
 * Logo de la marca del modelo dentro de un cuadrado redondeado teñido con su color.
 * Marcas sin icono vectorial disponible usan un glifo neutro o su inicial.
 */
@Composable
fun BrandLogo(brand: Brand, size: Dp = 28.dp, modifier: Modifier = Modifier) {
    val shape = RoundedCornerShape(size * 0.3f)
    Box(
        modifier = modifier
            .size(size)
            .clip(shape)
            .background(brand.color.copy(alpha = 0.16f)),
        contentAlignment = Alignment.Center
    ) {
        val d = pathFor(brand)
        when {
            d != null -> {
                val path = remember(d) { PathParser().parsePathString(d).toPath() }
                Canvas(modifier = Modifier.size(size * 0.58f)) {
                    val scale = this.size.width / 24f
                    withTransform({ scale(scale, scale, pivot = Offset.Zero) }) {
                        drawPath(path, brand.color)
                    }
                }
            }
            brand == Brand.OPENROUTER -> Icon(Icons.Default.Hub, null, tint = brand.color, modifier = Modifier.size(size * 0.58f))
            brand == Brand.AUTO -> Icon(Icons.Default.AutoAwesome, null, tint = brand.color, modifier = Modifier.size(size * 0.58f))
            else -> Text(
                text = brand.initial,
                color = brand.color,
                fontSize = (size.value * 0.42f).sp,
                fontWeight = FontWeight.Bold
            )
        }
    }
}
